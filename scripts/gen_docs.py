"""Render the command reference from `alphaengine.commands`.

    python scripts/gen_docs.py            # print the markdown block
    python scripts/gen_docs.py --write    # splice it into README.md
    python scripts/gen_docs.py --check    # fail if README.md is stale

── WHY THIS EXISTS ────────────────────────────────────────────────────────────

The command list is declared once in `src/alphaengine/commands.py` (`QOS-169`)
and rendered into the CLI parser, the interactive `commands` directory, and
`README.md`. `--check` runs in CI so command docs cannot drift from code.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "src"))

from alphaengine.commands import COMMANDS, DATA_DOORS, FLAGS, GROUPS  # noqa: E402

START = "<!-- COMMANDS:START -->"
END = "<!-- COMMANDS:END -->"
README = pathlib.Path(__file__).resolve().parents[1] / "README.md"


def _sig(c: object) -> str:
    verb = getattr(c, "verb", "")
    args = getattr(c, "args", "")
    return f"{verb} {args}".strip()


def _cell(text: str) -> str:
    r"""Escape pipe characters (`|`) inside markdown table cells."""
    return text.replace("|", r"\|")


def _locality_badge(locality: str) -> str:
    return {
        "local": "local",
        "remote": "remote",
        "hybrid": "local/remote",
    }.get(locality, locality)


def render() -> str:
    out: list[str] = [
        START,
        "<!-- Generated by scripts/gen_docs.py from src/alphaengine/commands.py.",
        "     Do not edit by hand; run `python scripts/gen_docs.py --write`. -->",
        "",
    ]

    for group, title in GROUPS:
        rows = [c for c in COMMANDS if c.group == group]
        if not rows:
            continue
        out += [f"### {title}", "", "| Command | Does | Boundary | Where |", "|---|---|---|---|"]
        for c in rows:
            where = {"both": "shell + session", "cli": "shell", "repl": "session"}[c.scope]
            bound = _locality_badge(c.locality)
            out.append(f"| `{_cell(_sig(c))}` | {_cell(c.purpose)} | `{bound}` | {where} |")
        out.append("")

    out += [
        "### Data flags",
        "",
        "| Flag | What it takes |",
        "|---|---|",
    ]
    for door, what in DATA_DOORS:
        out.append(f"| `{_cell(door)}` | {_cell(what)} |")
    out.append("")

    out += ["### Flags", "", "| Flag | Does |", "|---|---|"]
    for f in FLAGS.values():
        if f.deprecated:
            continue
        sig = f"{f.name} {f.takes}".strip()
        out.append(f"| `{_cell(sig)}` | {_cell(f.purpose)} |")
    out.append("")

    out += ["### Examples", "", "```bash"]
    for c in COMMANDS:
        for ex in c.examples:
            if ex.startswith("alphaengine"):
                out.append(ex)
    out += ["```", "", END]
    return "\n".join(out)


def splice(text: str, block: str) -> str:
    if START not in text or END not in text:
        raise SystemExit(
            f"README.md has no {START} / {END} markers. Add them where the command reference should live."
        )
    head = text.split(START)[0]
    tail = text.split(END, 1)[1]
    return head + block + tail


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true", help="splice into README.md")
    ap.add_argument("--check", action="store_true", help="fail if README.md is stale")
    args = ap.parse_args()

    block = render()

    if args.write:
        README.write_text(splice(README.read_text(encoding="utf-8"), block), encoding="utf-8")
        print(f"wrote {README}")
        return 0

    if args.check:
        current = README.read_text(encoding="utf-8")
        if splice(current, block) != current:
            print(
                "README.md's command block is stale.\n"
                "  A verb changed in src/alphaengine/commands.py and the README did not.\n"
                "  Run: python scripts/gen_docs.py --write",
                file=sys.stderr,
            )
            return 1
        print("README command block is current")
        return 0

    print(block)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
